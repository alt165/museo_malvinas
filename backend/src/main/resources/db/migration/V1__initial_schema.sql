CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    keycloak_id VARCHAR(100) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    CONSTRAINT uk_usuarios_keycloak_id UNIQUE (keycloak_id),
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE objetos_museo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    numero_inventario VARCHAR(80) NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    tipo_objeto VARCHAR(100),
    descripcion TEXT,
    CONSTRAINT uk_objetos_museo_numero_inventario UNIQUE (numero_inventario)
);

CREATE TABLE objetos_digitales (
    id BIGINT PRIMARY KEY,
    formato_digital VARCHAR(80),
    identificador_digital VARCHAR(120),
    metadatos TEXT,
    CONSTRAINT fk_objetos_digitales_objeto FOREIGN KEY (id) REFERENCES objetos_museo (id)
);

CREATE TABLE categoria_objeto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    CONSTRAINT uk_categoria_objeto_nombre UNIQUE (nombre)
);

CREATE TABLE objeto_categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    objeto_museo_id BIGINT NOT NULL,
    categoria_objeto_id BIGINT NOT NULL,
    observaciones TEXT,
    CONSTRAINT uk_objeto_categoria UNIQUE (objeto_museo_id, categoria_objeto_id),
    CONSTRAINT fk_objeto_categoria_objeto FOREIGN KEY (objeto_museo_id) REFERENCES objetos_museo (id),
    CONSTRAINT fk_objeto_categoria_categoria FOREIGN KEY (categoria_objeto_id) REFERENCES categoria_objeto (id)
);

CREATE TABLE depositantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    nombre VARCHAR(160) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    contacto VARCHAR(160),
    observaciones TEXT
);

CREATE TABLE objeto_depositante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    objeto_museo_id BIGINT NOT NULL,
    depositante_id BIGINT NOT NULL,
    fecha_deposito DATE,
    tipo_deposito VARCHAR(80),
    observaciones TEXT,
    CONSTRAINT uk_objeto_depositante UNIQUE (objeto_museo_id, depositante_id),
    CONSTRAINT fk_objeto_depositante_objeto FOREIGN KEY (objeto_museo_id) REFERENCES objetos_museo (id),
    CONSTRAINT fk_objeto_depositante_depositante FOREIGN KEY (depositante_id) REFERENCES depositantes (id)
);

CREATE TABLE veteranos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    fuerza VARCHAR(40) NOT NULL,
    fecha_nacimiento DATE,
    fecha_fallecimiento DATE,
    historia TEXT
);

CREATE TABLE actuaciones_veteranos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    veterano_id BIGINT NOT NULL,
    rango VARCHAR(80),
    unidad VARCHAR(120),
    rol VARCHAR(120),
    fecha_inicio DATE,
    fecha_fin DATE,
    descripcion TEXT,
    CONSTRAINT fk_actuaciones_veteranos_veterano FOREIGN KEY (veterano_id) REFERENCES veteranos (id)
);

CREATE TABLE objeto_veterano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    objeto_museo_id BIGINT NOT NULL,
    veterano_id BIGINT NOT NULL,
    tipo_relacion VARCHAR(100) NOT NULL,
    descripcion TEXT,
    CONSTRAINT uk_objeto_veterano_tipo UNIQUE (objeto_museo_id, veterano_id, tipo_relacion),
