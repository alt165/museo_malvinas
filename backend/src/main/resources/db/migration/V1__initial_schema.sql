    CONSTRAINT fk_objeto_veterano_veterano FOREIGN KEY (veterano_id) REFERENCES veteranos (id)
);

CREATE TABLE ubicaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    nombre VARCHAR(120) NOT NULL,
    tipo VARCHAR(80),
    descripcion TEXT,
    CONSTRAINT uk_ubicaciones_nombre UNIQUE (nombre)
);

CREATE TABLE inventarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    objeto_museo_id BIGINT NOT NULL,
    ubicacion_id BIGINT NOT NULL,
    estado VARCHAR(40) NOT NULL,
    estado_conservacion VARCHAR(40) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_salida DATE,
    fecha_ultimo_movimiento TIMESTAMP NOT NULL,
    observaciones TEXT,
    CONSTRAINT uk_inventarios_objeto_museo UNIQUE (objeto_museo_id),
    CONSTRAINT fk_inventarios_objeto FOREIGN KEY (objeto_museo_id) REFERENCES objetos_museo (id),
    CONSTRAINT fk_inventarios_ubicacion FOREIGN KEY (ubicacion_id) REFERENCES ubicaciones (id)
);

CREATE TABLE movimientos_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    objeto_museo_id BIGINT NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    ubicacion_origen_id BIGINT,
    ubicacion_destino_id BIGINT,
    usuario_id BIGINT,
    observaciones TEXT,
    CONSTRAINT fk_movimientos_inventario_objeto FOREIGN KEY (objeto_museo_id) REFERENCES objetos_museo (id),
    CONSTRAINT fk_movimientos_inventario_ubicacion_origen FOREIGN KEY (ubicacion_origen_id) REFERENCES ubicaciones (id),
    CONSTRAINT fk_movimientos_inventario_ubicacion_destino FOREIGN KEY (ubicacion_destino_id) REFERENCES ubicaciones (id),
    CONSTRAINT fk_movimientos_inventario_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE exhibiciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    nombre VARCHAR(160) NOT NULL,
    descripcion TEXT,
    tipo VARCHAR(30) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    estado VARCHAR(30) NOT NULL
);

CREATE TABLE exhibicion_objeto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    exhibicion_id BIGINT NOT NULL,
    objeto_museo_id BIGINT NOT NULL,
    fecha_inclusion DATE NOT NULL,
    fecha_retiro DATE,
    estado VARCHAR(40) NOT NULL,
    devolucion_verificada BOOLEAN NOT NULL DEFAULT FALSE,
    verificado_por_usuario_id BIGINT,
    fecha_verificacion TIMESTAMP,
    observaciones_devolucion TEXT,
    CONSTRAINT uk_exhibicion_objeto UNIQUE (exhibicion_id, objeto_museo_id),
    CONSTRAINT fk_exhibicion_objeto_exhibicion FOREIGN KEY (exhibicion_id) REFERENCES exhibiciones (id),
    CONSTRAINT fk_exhibicion_objeto_objeto FOREIGN KEY (objeto_museo_id) REFERENCES objetos_museo (id),
    CONSTRAINT fk_exhibicion_objeto_usuario FOREIGN KEY (verificado_por_usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE relaciones_objetos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    objeto_origen_id BIGINT NOT NULL,
    objeto_destino_id BIGINT NOT NULL,
    tipo_relacion VARCHAR(80) NOT NULL,
    descripcion TEXT,
    CONSTRAINT uk_relacion_objeto_direccional UNIQUE (objeto_origen_id, objeto_destino_id, tipo_relacion),
    CONSTRAINT fk_relaciones_objetos_origen FOREIGN KEY (objeto_origen_id) REFERENCES objetos_museo (id),
    CONSTRAINT fk_relaciones_objetos_destino FOREIGN KEY (objeto_destino_id) REFERENCES objetos_museo (id)
);

CREATE TABLE auditorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_id BIGINT,
    fecha TIMESTAMP NOT NULL,
    tipo_operacion VARCHAR(30) NOT NULL,
    entidad VARCHAR(120) NOT NULL,
    entidad_id BIGINT NOT NULL,
    datos_previos TEXT,
    datos_nuevos TEXT,
    CONSTRAINT fk_auditorias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

